//! Safe shortest-round-trip core for `f64` and `f32` (Schubfach-class).
//!
//! Given the IEEE fields of a finite nonzero float, `shortest` returns `(m, e)` such that
//! `m * 10^e` is the decimal of shortest length that rounds back to the same float, and, among
//! decimals of that length, the one closest to the exact value (ties to even). `m` has
//! trailing zeros removed (`m` is not a multiple of 10).
//!
//! No raw pointers, no escape hatches from the borrow checker, no traits, no iterators, no allocation: array indexing, integer
//! arithmetic (one `u64 x u64 -> u128` multiply per bound) and `if`, the subset Charon and Aeneas
//! translate. Proved in `proofs/lean`: the table is exact, no multiplication overflows, the shifts
//! and indices are in range for every `f64` and `f32` exponent. The full statement "shortest and
//! closest" is NOT proved; it is evidenced by the exhaustive `f32` sweep and the `f64` differential
//! tests (`tests/float_diff.rs`).
//!
//! Method: Raffaello Giulietti, "The Schubfach way to render doubles" (2020). This is an
//! independent implementation of the published algorithm; the power-of-ten table is generated by
//! `tests/float_tables.rs` from exact big-integer arithmetic.
//!
//! Scaling. For `v = c * 2^q` choose `k` with `10^k <= 2^q` (or `<= 3/4 * 2^q` when the lower
//! neighbour is closer), so that `X = v / 10^k` has an interval of length at least one around it.
//! `G[-k - J_MIN]` is `g = ceil(10^-k * 2^(125 - f))`, `f = floor(log2 10^-k)`, a number in
//! `[2^125, 2^126]`; `rop(g, cb << h)` with `h = q + f + 1` is `4X` rounded to odd.

pub use super::float_tables::{G, J_MAX, J_MIN};

/// `floor(log10(2^q))`, exact for `|q| <= 1650` (checked in `tests/float_tables.rs`).
#[inline(always)]
pub fn flog10_pow2(q: i32) -> i32 {
    (((q as i64) * 661_971_961_083) >> 41) as i32
}

/// `floor(log10(3/4 * 2^q))`, exact for `|q| <= 1650`.
#[inline(always)]
pub fn flog10_three_quarters_pow2(q: i32) -> i32 {
    (((q as i64) * 661_971_961_083 - 274_743_187_321) >> 41) as i32
}

/// `floor(log2(10^e))`, exact for `|e| <= 500`.
#[inline(always)]
pub fn flog2_pow10(e: i32) -> i32 {
    (((e as i64) * 913_124_641_741) >> 38) as i32
}

/// `floor(cp * g / 2^126)` rounded to odd, where `g = ghi * 2^64 + glo < 2^126` and `cp < 2^63`.
///
/// Rounding to odd means: if the quotient is not exact, its lowest bit is forced to 1.
#[inline(always)]
pub fn rop(ghi: u64, glo: u64, cp: u64) -> u64 {
    let t0 = (cp as u128) * (glo as u128);
    let t1 = (cp as u128) * (ghi as u128);
    // floor(cp * g / 2^64); t1 < 2^63 * 2^62 and t0 >> 64 < 2^63, so no overflow
    let x = t1 + (t0 >> 64);
    let vb = (x >> 62) as u64;
    let sticky = ((x & 0x3fff_ffff_ffff_ffff) != 0) | ((t0 as u64) != 0);
    vb | (sticky as u64)
}

/// Shortest decimal `(m, e)`, value `m * 10^e`, of `c * 2^q` where `c` is the integer significand.
///
/// `c_min` is the smallest normal significand (`2^52` / `2^23`) and `q_min` the smallest exponent
/// (`-1074` / `-149`); `c` is nonzero.
#[inline]
pub fn shortest(c: u64, q: i32, c_min: u64, q_min: i32, tie_even: bool) -> (u64, i32) {
    let out = c & 1; // 1 when the endpoints of the rounding interval are excluded (odd c)
    let cb = c << 2;
    let cbr = cb + 2;
    let regular = (c != c_min) | (q == q_min);
    let cbl = if regular { cb - 2 } else { cb - 1 };
    let k = if regular {
        flog10_pow2(q)
    } else {
        flog10_three_quarters_pow2(q)
    };
    let h = q + flog2_pow10(-k) + 1;
    let gi = ((-k - J_MIN) as usize) * 2;
    let g = [G[gi], G[gi + 1]];
    // `g` over-estimates the exact power of ten except when it is exact (10^j, 0 <= j <= 53, i.e.
    // -53 <= k <= 0). The exact scaled endpoints of the rounding interval can be integers when
    // 0 < k <= 23; there the comparison below must lean away from `g`'s error: an included
    // endpoint needs the under-estimate, an excluded one the over-estimate.
    let inexact = (k < -53) | (k > 0);
    let g_over = ((g[0] as u128) << 64) | (g[1] as u128);
    let g_under = g_over - (inexact as u128);
    let closed = out == 0;
    let g_lo = if closed { g_under } else { g_over };
    let g_hi = if closed { g_over } else { g_under };
    let vb = rop(g[0], g[1], cb << h);
    let vbl = rop((g_lo >> 64) as u64, g_lo as u64, cbl << h);
    let vbr = rop((g_hi >> 64) as u64, g_hi as u64, cbr << h);
    let s = vb >> 2;
    {
        // is there a multiple of 10 in the interval? then one digit fewer
        let sp10 = 10 * (s / 10);
        let tp10 = sp10 + 10;
        let upin = vbl + out <= (sp10 << 2);
        let wpin = (tp10 << 2) + out <= vbr;
        if upin != wpin {
            return strip_zeros(if upin { sp10 } else { tp10 }, k);
        }
    }
    let t = s + 1;
    let uin = vbl + out <= (s << 2);
    let win = (t << 2) + out <= vbr;
    if uin != win {
        return (if uin { s } else { t }, k);
    }
    // both inside: the closer to v wins; an exact tie goes to the even s when `tie_even`, else up
    let twice = (s + t) << 1;
    if vb < twice || (vb == twice && tie_even && (s & 1) == 0) {
        (s, k)
    } else {
        (t, k)
    }
}

/// Shortest decimal of a finite nonzero `f64` from its IEEE fields (`mant` 52 bits, `exp` 11 bits).
#[inline]
pub fn dec_f64(mant: u64, exp: u32, tie_even: bool) -> (u64, i32) {
    if exp == 0 {
        shortest(mant, -1074, 1 << 52, -1074, tie_even)
    } else {
        shortest(
            mant | (1 << 52),
            (exp as i32) - 1075,
            1 << 52,
            -1074,
            tie_even,
        )
    }
}

/// Shortest decimal of a finite nonzero `f32` from its IEEE fields (`mant` 23 bits, `exp` 8 bits).
#[inline]
pub fn dec_f32(mant: u32, exp: u32, tie_even: bool) -> (u64, i32) {
    if exp == 0 {
        shortest(mant as u64, -149, 1 << 23, -149, tie_even)
    } else {
        shortest(
            (mant | (1 << 23)) as u64,
            (exp as i32) - 150,
            1 << 23,
            -149,
            tie_even,
        )
    }
}

/// Remove all trailing decimal zeros of `m` (`0 < m < 10^18`), adding their number to `e`.
///
/// Greedy binary decomposition: `m` has at most 17 trailing zeros, so testing `10^16`, `10^8`,
/// `10^4`, `10^2`, `10^1` in that order removes them all (each level sees fewer than twice its size).
#[inline(always)]
pub fn strip_zeros(m: u64, e: i32) -> (u64, i32) {
    let mut m = m;
    let mut e = e;
    if m % 10_000_000_000_000_000 == 0 {
        m /= 10_000_000_000_000_000;
        e += 16;
    }
    if m % 100_000_000 == 0 {
        m /= 100_000_000;
        e += 8;
    }
    if m % 10_000 == 0 {
        m /= 10_000;
        e += 4;
    }
    if m % 100 == 0 {
        m /= 100;
        e += 2;
    }
    if m % 10 == 0 {
        m /= 10;
        e += 1;
    }
    (m, e)
}
