//! Python emitter: dataclasses and `Enum`s plus `decode_*`/`encode_*` functions over plain
//! JSON-compatible objects (`json.loads` output), standard library only.

use super::{dedupe, field_names, safe_ident};
use crate::schema::{Def, EnumRepr, Field, Named, Schema, Ty, VariantKind};
use std::fmt::Write;

const RESERVED: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue",
    "def", "del", "elif", "else", "except", "finally", "for", "from", "global", "if", "import",
    "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while",
    "with", "yield", "self", "match", "case", "type",
];

const PRELUDE: &str = r#"# Generated by wirefold::facet::emit::python. Do not edit.
#
# Reads and writes the JSON wire form of the Rust types: `decode_X(json.loads(text))` and
# `json.dumps(encode_X(value))`. Standard library only.
from __future__ import annotations

import enum
import json
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple, Union


def _fail(what: str, o: Any) -> "ValueError":
    return ValueError(f"expected {what}, got {type(o).__name__}: {o!r:.80}")


def _null(o: Any) -> None:
    if o is not None:
        raise _fail("null", o)
    return None


def _bool(o: Any) -> bool:
    if not isinstance(o, bool):
        raise _fail("bool", o)
    return o


def _int(o: Any) -> int:
    if isinstance(o, bool) or not isinstance(o, int):
        if isinstance(o, float) and o.is_integer():
            return int(o)
        raise _fail("integer", o)
    return o


def _bigint(o: Any) -> int:
    if isinstance(o, str):
        return int(o)
    return _int(o)


def _float(o: Any) -> float:
    if isinstance(o, bool) or not isinstance(o, (int, float)):
        raise _fail("number", o)
    return float(o)


def _str(o: Any) -> str:
    if not isinstance(o, str):
        raise _fail("string", o)
    return o


def _list(o: Any) -> list:
    if not isinstance(o, list):
        raise _fail("array", o)
    return o


def _tuple(o: Any, n: int) -> list:
    o = _list(o)
    if len(o) != n:
        raise ValueError(f"expected an array of {n} items, got {len(o)}")
    return o


def _obj(o: Any, what: str) -> dict:
    if not isinstance(o, dict):
        raise _fail(f"object ({what})", o)
    return o


def _req(o: dict, key: str, what: str) -> Any:
    if key not in o:
        raise ValueError(f"{what}: missing field {key!r}")
    return o[key]

"#;

/// Emit Python source for every definition in `schema`.
#[must_use]
pub fn python(schema: &Schema) -> String {
    let mut out = String::from(PRELUDE);
    for w in &schema.warnings {
        let _ = writeln!(out, "# warning: {w}");
    }
    for d in &schema.defs {
        out.push('\n');
        emit_def(&mut out, d);
    }
    out
}

fn doc(out: &mut String, lines: &[String], indent: &str) {
    if lines.is_empty() {
        return;
    }
    let text = lines
        .join(&format!("\n{indent}"))
        .replace("\"\"\"", "'''")
        .replace('\\', "\\\\");
    let _ = writeln!(out, "{indent}\"\"\"{text}\"\"\"");
}

fn ty(t: &Ty) -> String {
    match t {
        Ty::Null => "None".into(),
        Ty::Bool => "bool".into(),
        Ty::Int { .. } | Ty::BigInt { .. } => "int".into(),
        Ty::Float { .. } => "float".into(),
        Ty::String => "str".into(),
        Ty::Option(i) => format!("Optional[{}]", ty(i)),
        Ty::List(i) => format!("List[{}]", ty(i)),
        Ty::Map(i) => format!("Dict[str, {}]", ty(i)),
        Ty::Tuple(items) if items.is_empty() => "Tuple[()]".into(),
        Ty::Tuple(items) => format!(
            "Tuple[{}]",
            items.iter().map(ty).collect::<Vec<_>>().join(", ")
        ),
        Ty::Ref(n) => n.clone(),
        Ty::Any => "Any".into(),
    }
}

/// An expression decoding the JSON value `e` (a simple expression, evaluated more than once only
/// inside a lambda that binds it) to type `t`.
fn dec(t: &Ty, e: &str, d: usize) -> String {
    match t {
        Ty::Null => format!("_null({e})"),
        Ty::Bool => format!("_bool({e})"),
        Ty::Int { .. } => format!("_int({e})"),
        Ty::BigInt { .. } => format!("_bigint({e})"),
        Ty::Float { .. } => format!("_float({e})"),
        Ty::String => format!("_str({e})"),
        Ty::Option(i) => {
            let v = format!("_o{d}");
            format!(
                "(lambda {v}: None if {v} is None else {})({e})",
                dec(i, &v, d + 1)
            )
        }
        Ty::List(i) => {
            let v = format!("_x{d}");
            format!("[{} for {v} in _list({e})]", dec(i, &v, d + 1))
        }
        Ty::Map(i) => {
            let (k, v) = (format!("_k{d}"), format!("_v{d}"));
            format!(
                "{{{k}: {} for {k}, {v} in _obj({e}, 'map').items()}}",
                dec(i, &v, d + 1)
            )
        }
        Ty::Tuple(items) => {
            let v = format!("_t{d}");
            let parts: Vec<String> = items
                .iter()
                .enumerate()
                .map(|(i, it)| dec(it, &format!("{v}[{i}]"), d + 1))
                .collect();
            let tuple = if parts.len() == 1 {
                format!("({},)", parts[0])
            } else {
                format!("({})", parts.join(", "))
            };
            format!("(lambda {v}: {tuple})(_tuple({e}, {}))", items.len())
        }
        Ty::Ref(n) => format!("decode_{n}({e})"),
        Ty::Any => e.to_owned(),
    }
}

fn enc(t: &Ty, e: &str, d: usize) -> String {
    match t {
        Ty::Null | Ty::Bool | Ty::Int { .. } | Ty::Float { .. } | Ty::String | Ty::Any => {
            e.to_owned()
        }
        Ty::BigInt { .. } => format!("str({e})"),
        Ty::Option(i) => {
            let v = format!("_o{d}");
            format!(
                "(lambda {v}: None if {v} is None else {})({e})",
                enc(i, &v, d + 1)
            )
        }
        Ty::List(i) => {
            let v = format!("_x{d}");
            format!("[{} for {v} in {e}]", enc(i, &v, d + 1))
        }
        Ty::Map(i) => {
            let (k, v) = (format!("_k{d}"), format!("_v{d}"));
            format!("{{{k}: {} for {k}, {v} in {e}.items()}}", enc(i, &v, d + 1))
        }
        Ty::Tuple(items) => {
            let v = format!("_t{d}");
            let parts: Vec<String> = items
                .iter()
                .enumerate()
                .map(|(i, it)| enc(it, &format!("{v}[{i}]"), d + 1))
                .collect();
            format!("(lambda {v}: [{}])({e})", parts.join(", "))
        }
        Ty::Ref(n) => format!("encode_{n}({e})"),
    }
}

fn py_name(s: &str) -> String {
    safe_ident(s, RESERVED)
}

fn convenience(out: &mut String, name: &str) {
    let _ = write!(
        out,
        "\n    @staticmethod\n    def from_obj(o: Any) -> \"{name}\":\n        return decode_{name}(o)\n\n    def to_obj(self) -> Any:\n        return encode_{name}(self)\n\n    @staticmethod\n    def from_json(s: str) -> \"{name}\":\n        return decode_{name}(json.loads(s))\n\n    def to_json(self) -> str:\n        return json.dumps(encode_{name}(self))\n"
    );
}

fn struct_fields(out: &mut String, fields: &[Field], names: &[String]) {
    if fields.is_empty() {
        out.push_str("    pass\n");
    }
    for (f, n) in fields.iter().zip(names) {
        let _ = writeln!(out, "    {n}: {}", ty(&f.ty));
        if !f.doc.is_empty() {
            let _ = writeln!(out, "    # {}", f.doc.join(" "));
        }
    }
}

/// `Cls(a=..., b=...)` decoding the object `o` (an identifier).
fn decode_fields(fields: &[Field], names: &[String], what: &str) -> String {
    let parts: Vec<String> = fields
        .iter()
        .zip(names)
        .map(|(f, n)| {
            let key = json_str(&f.name);
            let src = if f.optional() {
                format!("o.get({key})")
            } else {
                format!("_req(o, {key}, {})", json_str(what))
            };
            format!("{n}={}", dec(&f.ty, &src, 0))
        })
        .collect();
    parts.join(", ")
}

fn encode_fields(fields: &[Field], names: &[String], var: &str) -> String {
    let parts: Vec<String> = fields
        .iter()
        .zip(names)
        .map(|(f, n)| {
            format!(
                "{}: {}",
                json_str(&f.name),
                enc(&f.ty, &format!("{var}.{n}"), 0)
            )
        })
        .collect();
    parts.join(", ")
}

fn json_str(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c if (c as u32) < 0x20 => {
                let _ = write!(o, "\\u{:04x}", c as u32);
            }
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn emit_def(out: &mut String, d: &Named) {
    let name = &d.name;
    match &d.def {
        Def::Struct { fields } => {
            let names = field_names(fields, py_name);
            let _ = writeln!(out, "\n@dataclass\nclass {name}:");
            doc(out, &d.doc, "    ");
            struct_fields(out, fields, &names);
            convenience(out, name);
            let _ = writeln!(
                out,
                "\n\ndef decode_{name}(o: Any) -> {name}:\n    o = _obj(o, {})\n    return {name}({})\n\n\ndef encode_{name}(v: {name}) -> Any:\n    return {{{}}}",
                json_str(name),
                decode_fields(fields, &names, name),
                encode_fields(fields, &names, "v")
            );
        }
        Def::Tuple { items } => {
            let names: Vec<String> = (0..items.len()).map(|i| format!("f{i}")).collect();
            let _ = writeln!(out, "\n@dataclass\nclass {name}:");
            doc(out, &d.doc, "    ");
            if items.is_empty() {
                out.push_str("    pass\n");
            }
            for (n, t) in names.iter().zip(items) {
                let _ = writeln!(out, "    {n}: {}", ty(t));
            }
            convenience(out, name);
            let dec_parts: Vec<String> = items
                .iter()
                .enumerate()
                .map(|(i, t)| dec(t, &format!("o[{i}]"), 0))
                .collect();
            let enc_parts: Vec<String> = items
                .iter()
                .zip(&names)
                .map(|(t, n)| enc(t, &format!("v.{n}"), 0))
                .collect();
            let _ = writeln!(
                out,
                "\n\ndef decode_{name}(o: Any) -> {name}:\n    o = _tuple(o, {})\n    return {name}({})\n\n\ndef encode_{name}(v: {name}) -> Any:\n    return [{}]",
                items.len(),
                dec_parts.join(", "),
                enc_parts.join(", ")
            );
        }
        Def::Enum { repr, variants } => {
            if d.def.is_unit_enum() {
                let _ = writeln!(out, "\nclass {name}(str, enum.Enum):");
                doc(out, &d.doc, "    ");
                let members = dedupe(variants.iter().map(|v| py_name(&v.name)).collect());
                if variants.is_empty() {
                    out.push_str("    pass\n");
                }
                for (v, m) in variants.iter().zip(&members) {
                    let _ = writeln!(out, "    {m} = {}", json_str(&v.name));
                }
                let _ = writeln!(
                    out,
                    "\n\ndef decode_{name}(o: Any) -> {name}:\n    return {name}(_str(o))\n\n\ndef encode_{name}(v: {name}) -> Any:\n    return v.value"
                );
                return;
            }
            emit_data_enum(out, d, repr, variants);
        }
    }
}

fn emit_data_enum(
    out: &mut String,
    d: &Named,
    repr: &EnumRepr,
    variants: &[crate::schema::Variant],
) {
    let name = &d.name;
    let cls: Vec<String> = dedupe(
        variants
            .iter()
            .map(|v| format!("{name}{}", super::pascal(&v.name)))
            .collect(),
    );
    // One dataclass per variant.
    let mut payload_names: Vec<Vec<String>> = Vec::new();
    for (v, c) in variants.iter().zip(&cls) {
        let _ = writeln!(out, "\n@dataclass\nclass {c}:");
        doc(out, &v.doc, "    ");
        let names: Vec<String> = match &v.kind {
            VariantKind::Unit => {
                out.push_str("    pass\n");
                Vec::new()
            }
            VariantKind::Newtype(t) => {
                let _ = writeln!(out, "    value: {}", ty(t));
                vec!["value".into()]
            }
            VariantKind::Tuple(items) => {
                let names: Vec<String> = (0..items.len()).map(|i| format!("f{i}")).collect();
                for (n, t) in names.iter().zip(items) {
                    let _ = writeln!(out, "    {n}: {}", ty(t));
                }
                names
            }
            VariantKind::Struct(fields) => {
                let names = field_names(fields, py_name);
                struct_fields(out, fields, &names);
                names
            }
        };
        payload_names.push(names);
    }
    let _ = writeln!(out, "\n{name} = Union[{}]", cls.join(", "));
    if !d.doc.is_empty() {
        let _ = writeln!(out, "# {}", d.doc.join(" "));
    }
    let _ = writeln!(out, "\n\ndef decode_{name}(o: Any) -> {name}:");
    let what = json_str(name);
    match repr {
        EnumRepr::External => {
            let unit: Vec<_> = variants
                .iter()
                .zip(&cls)
                .filter(|(v, _)| v.kind == VariantKind::Unit)
                .collect();
            out.push_str("    if isinstance(o, str):\n");
            for (v, c) in &unit {
                let _ = writeln!(
                    out,
                    "        if o == {}:\n            return {c}()",
                    json_str(&v.name)
                );
            }
            let _ = writeln!(
                out,
                "        raise ValueError(f\"{name}: unknown variant {{o!r}}\")"
            );
            let _ = writeln!(
                out,
                "    o = _obj(o, {what})\n    if len(o) != 1:\n        raise ValueError(\"{name}: expected an object with exactly one key\")\n    (k, p), = o.items()"
            );
            for ((v, c), names) in variants.iter().zip(&cls).zip(&payload_names) {
                let key = json_str(&v.name);
                match &v.kind {
                    VariantKind::Unit => continue,
                    VariantKind::Newtype(t) => {
                        let _ = writeln!(
                            out,
                            "    if k == {key}:\n        return {c}(value={})",
                            dec(t, "p", 0)
                        );
                    }
                    VariantKind::Tuple(items) => {
                        let parts: Vec<String> = items
                            .iter()
                            .enumerate()
                            .map(|(i, t)| {
                                format!("{}={}", names[i], dec(t, &format!("_p[{i}]"), 0))
                            })
                            .collect();
                        let _ = writeln!(
                            out,
                            "    if k == {key}:\n        _p = _tuple(p, {})\n        return {c}({})",
                            items.len(),
                            parts.join(", ")
                        );
                    }
                    VariantKind::Struct(fields) => {
                        let _ = writeln!(
                            out,
                            "    if k == {key}:\n        o = _obj(p, {key})\n        return {c}({})",
                            decode_fields(fields, names, &v.name)
                        );
                    }
                }
            }
            let _ = writeln!(
                out,
                "    raise ValueError(f\"{name}: unknown variant {{k!r}}\")"
            );
        }
        EnumRepr::Internal { tag } => {
            let _ = writeln!(
                out,
                "    o = _obj(o, {what})\n    k = _req(o, {}, {what})",
                json_str(tag)
            );
            for ((v, c), names) in variants.iter().zip(&cls).zip(&payload_names) {
                let key = json_str(&v.name);
                match &v.kind {
                    VariantKind::Unit => {
                        let _ = writeln!(out, "    if k == {key}:\n        return {c}()");
                    }
                    VariantKind::Struct(fields) => {
                        let _ = writeln!(
                            out,
                            "    if k == {key}:\n        return {c}({})",
                            decode_fields(fields, names, &v.name)
                        );
                    }
                    VariantKind::Newtype(t) if super::is_ref(t) => {
                        let _ = writeln!(
                            out,
                            "    if k == {key}:\n        return {c}(value={})",
                            dec(t, "o", 0)
                        );
                    }
                    _ => {
                        let _ = writeln!(
                            out,
                            "    if k == {key}:\n        raise ValueError(\"{name}.{}: an internally tagged variant must be a struct\")",
                            v.name.replace('"', "")
                        );
                    }
                }
            }
            let _ = writeln!(
                out,
                "    raise ValueError(f\"{name}: unknown variant {{k!r}}\")"
            );
        }
        EnumRepr::Adjacent { tag, content } => {
            let _ = writeln!(
                out,
                "    o = _obj(o, {what})\n    k = _req(o, {}, {what})\n    p = o.get({})",
                json_str(tag),
                json_str(content)
            );
            for ((v, c), names) in variants.iter().zip(&cls).zip(&payload_names) {
                let key = json_str(&v.name);
                match &v.kind {
                    VariantKind::Unit => {
                        let _ = writeln!(out, "    if k == {key}:\n        return {c}()");
                    }
                    VariantKind::Newtype(t) => {
                        let _ = writeln!(
                            out,
                            "    if k == {key}:\n        return {c}(value={})",
                            dec(t, "p", 0)
                        );
                    }
                    VariantKind::Tuple(items) => {
                        let parts: Vec<String> = items
                            .iter()
                            .enumerate()
                            .map(|(i, t)| {
                                format!("{}={}", names[i], dec(t, &format!("_p[{i}]"), 0))
                            })
                            .collect();
                        let _ = writeln!(out, "    if k == {key}:\n        _p = _tuple(p, {})\n        return {c}({})", items.len(), parts.join(", "));
                    }
                    VariantKind::Struct(fields) => {
                        let _ = writeln!(out, "    if k == {key}:\n        o = _obj(p, {key})\n        return {c}({})", decode_fields(fields, names, &v.name));
                    }
                }
            }
            let _ = writeln!(
                out,
                "    raise ValueError(f\"{name}: unknown variant {{k!r}}\")"
            );
        }
    }

    // encode
    let _ = writeln!(out, "\n\ndef encode_{name}(v: {name}) -> Any:");
    for ((v, c), names) in variants.iter().zip(&cls).zip(&payload_names) {
        let key = json_str(&v.name);
        let _ = writeln!(out, "    if isinstance(v, {c}):");
        let body = match (&v.kind, repr) {
            (VariantKind::Unit, EnumRepr::External) => key.clone(),
            (VariantKind::Unit, EnumRepr::Internal { tag } | EnumRepr::Adjacent { tag, .. }) => {
                format!("{{{}: {key}}}", json_str(tag))
            }
            (kind, _) => {
                let payload = match kind {
                    VariantKind::Unit => "None".to_owned(),
                    VariantKind::Newtype(t) => enc(t, "v.value", 0),
                    VariantKind::Tuple(items) => format!(
                        "[{}]",
                        items
                            .iter()
                            .zip(names)
                            .map(|(t, n)| enc(t, &format!("v.{n}"), 0))
                            .collect::<Vec<_>>()
                            .join(", ")
                    ),
                    VariantKind::Struct(fields) => {
                        format!("{{{}}}", encode_fields(fields, names, "v"))
                    }
                };
                match repr {
                    EnumRepr::External => format!("{{{key}: {payload}}}"),
                    EnumRepr::Adjacent { tag, content } => {
                        format!("{{{}: {key}, {}: {payload}}}", json_str(tag), json_str(content))
                    }
                    EnumRepr::Internal { tag } => match kind {
                        VariantKind::Struct(_) => format!("{{{}: {key}, **{payload}}}", json_str(tag)),
                        VariantKind::Newtype(t) if super::is_ref(t) => {
                            format!("{{{}: {key}, **{payload}}}", json_str(tag))
                        }
                        _ => format!(
                            "(_ for _ in ()).throw(ValueError(\"{name}: an internally tagged variant must be a struct\"))"
                        ),
                    },
                }
            }
        };
        let _ = writeln!(out, "        return {body}");
    }
    let _ = writeln!(
        out,
        "    raise ValueError(f\"{name}: not a variant: {{v!r}}\")"
    );
    let _ = write!(
        out,
        "\n\ndef {}_from_json(s: str) -> {name}:\n    return decode_{name}(json.loads(s))\n\n\ndef {}_to_json(v: {name}) -> str:\n    return json.dumps(encode_{name}(v))\n",
        snake(name),
        snake(name)
    );
}

fn snake(s: &str) -> String {
    let mut o = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                o.push('_');
            }
            o.push(c.to_ascii_lowercase());
        } else {
            o.push(c);
        }
    }
    o
}
