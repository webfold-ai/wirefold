//! Go emitter: structs with `json` tags, and `MarshalJSON`/`UnmarshalJSON` for enums and tuples,
//! standard library only.
//!
//! Choices a Go reader may want to know about: `Option<T>` is `*T` (marshalled as `null` when
//! nil); `Vec<u8>` is `[]int`, because `[]byte` marshals as base64; tuples are `[]any` where they
//! appear inline and a struct with `F0`, `F1`, ... where they are a named tuple struct or a tuple
//! variant; a 128-bit integer is a decimal `string`.

use super::{dedupe, field_names, pascal};
use crate::schema::{Def, EnumRepr, Field, Named, Schema, Ty, Variant, VariantKind};
use std::fmt::Write;

const HELPERS: &str = r#"
// wfTagged marshals payload and adds the internal tag.
func wfTagged(tag, name string, payload any) ([]byte, error) {
	b, err := json.Marshal(payload)
	if err != nil {
		return nil, err
	}
	m := map[string]json.RawMessage{}
	if string(b) != "null" {
		if err := json.Unmarshal(b, &m); err != nil {
			return nil, err
		}
	}
	t, _ := json.Marshal(name)
	m[tag] = t
	return json.Marshal(m)
}

// wfTag reads the string stored under tag.
func wfTag(m map[string]json.RawMessage, tag, what string) (string, error) {
	raw, ok := m[tag]
	if !ok {
		return "", fmt.Errorf("%s: missing tag %q", what, tag)
	}
	var s string
	if err := json.Unmarshal(raw, &s); err != nil {
		return "", fmt.Errorf("%s: tag %q: %w", what, tag, err)
	}
	return s, nil
}
"#;

/// Emit Go source for every definition in `schema`, in package `package`.
#[must_use]
pub fn go(schema: &Schema, package: &str) -> String {
    let mut out = format!(
        "// Code generated by wirefold::facet::emit::go. DO NOT EDIT.\n//\n// Reads and writes the JSON wire form of the Rust types with encoding/json.\n\npackage {package}\n\nimport (\n\t\"encoding/json\"\n\t\"errors\"\n\t\"fmt\"\n)\n\nvar (\n\t_ = errors.New\n\t_ = fmt.Errorf\n\t_ = json.Marshal\n)\n"
    );
    for w in &schema.warnings {
        let _ = writeln!(out, "// warning: {w}");
    }
    out.push_str(HELPERS);
    for d in &schema.defs {
        out.push('\n');
        emit_def(&mut out, d);
    }
    out
}

fn ty(t: &Ty) -> String {
    match t {
        Ty::Null | Ty::Any => "any".into(),
        Ty::Bool => "bool".into(),
        Ty::Int { bits, signed } => format!("{}int{bits}", if *signed { "" } else { "u" }),
        Ty::BigInt { .. } | Ty::String => "string".into(),
        Ty::Float { bits } => format!("float{bits}"),
        Ty::Option(i) => format!("*{}", ty(i)),
        // `[]uint8` marshals as base64, which is not the wire form of a `Vec<u8>`.
        Ty::List(i)
            if matches!(
                **i,
                Ty::Int {
                    bits: 8,
                    signed: false
                }
            ) =>
        {
            "[]int".into()
        }
        Ty::List(i) => format!("[]{}", ty(i)),
        Ty::Map(i) => format!("map[string]{}", ty(i)),
        Ty::Tuple(_) => "[]any".into(),
        Ty::Ref(n) => cap(n),
    }
}

fn cap(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_ascii_uppercase().to_string() + c.as_str(),
        None => String::new(),
    }
}

fn q(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c if (c as u32) < 0x20 => {
                let _ = write!(o, "\\u{:04x}", c as u32);
            }
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn comment(out: &mut String, lines: &[String], indent: &str) {
    for l in lines {
        let _ = writeln!(out, "{indent}// {l}");
    }
}

fn struct_body(out: &mut String, fields: &[Field], names: &[String]) {
    for (f, n) in fields.iter().zip(names) {
        comment(out, &f.doc, "\t");
        let _ = writeln!(out, "\t{n} {} `json:{}`", ty(&f.ty), q(&f.name));
    }
}

/// A struct type with `F0`, `F1`, ... fields that marshals as a JSON array.
fn tuple_type(out: &mut String, name: &str, items: &[Ty], doc: &[String]) {
    comment(out, doc, "");
    let _ = writeln!(out, "type {name} struct {{");
    for (i, t) in items.iter().enumerate() {
        let _ = writeln!(out, "\tF{i} {}", ty(t));
    }
    let _ = writeln!(out, "}}\n");
    let list: Vec<String> = (0..items.len()).map(|i| format!("v.F{i}")).collect();
    let _ = writeln!(
        out,
        "func (v {name}) MarshalJSON() ([]byte, error) {{\n\treturn json.Marshal([]any{{{}}})\n}}\n",
        list.join(", ")
    );
    let _ = writeln!(
        out,
        "func (v *{name}) UnmarshalJSON(b []byte) error {{\n\tvar a []json.RawMessage\n\tif err := json.Unmarshal(b, &a); err != nil {{\n\t\treturn err\n\t}}\n\tif len(a) != {} {{\n\t\treturn fmt.Errorf(\"{name}: expected {} items, got %d\", len(a))\n\t}}",
        items.len(),
        items.len()
    );
    for i in 0..items.len() {
        let _ = writeln!(
            out,
            "\tif err := json.Unmarshal(a[{i}], &v.F{i}); err != nil {{\n\t\treturn err\n\t}}"
        );
    }
    out.push_str("\treturn nil\n}\n");
}

fn emit_def(out: &mut String, d: &Named) {
    let name = cap(&d.name);
    match &d.def {
        Def::Struct { fields } => {
            let names = field_names(fields, pascal);
            comment(out, &d.doc, "");
            let _ = writeln!(out, "type {name} struct {{");
            struct_body(out, fields, &names);
            out.push_str("}\n");
        }
        Def::Tuple { items } => tuple_type(out, &name, items, &d.doc),
        Def::Enum { repr, variants } => {
            if d.def.is_unit_enum() {
                comment(out, &d.doc, "");
                let _ = writeln!(out, "type {name} string\n\nconst (");
                let consts = dedupe(
                    variants
                        .iter()
                        .map(|v| format!("{name}{}", pascal(&v.name)))
                        .collect(),
                );
                let consts: Vec<String> = consts;
                for (v, c) in variants.iter().zip(&consts) {
                    comment(out, &v.doc, "\t");
                    let _ = writeln!(out, "\t{c} {name} = {}", q(&v.name));
                }
                let _ = writeln!(out, ")\n");
                let cases: Vec<&String> = consts.iter().collect();
                let _ = writeln!(
                    out,
                    "func (v *{name}) UnmarshalJSON(b []byte) error {{\n\tvar s string\n\tif err := json.Unmarshal(b, &s); err != nil {{\n\t\treturn err\n\t}}\n\tswitch {name}(s) {{\n\tcase {}:\n\t\t*v = {name}(s)\n\t\treturn nil\n\t}}\n\treturn fmt.Errorf(\"{name}: unknown variant %q\", s)\n}}",
                    if cases.is_empty() { "\"\"".to_owned() } else { cases.iter().map(|c| c.as_str()).collect::<Vec<_>>().join(", ") }
                );
                return;
            }
            emit_data_enum(out, &name, &d.doc, repr, variants);
        }
    }
}

/// How one variant is held in the Go struct.
struct Slot {
    /// The exported field name.
    field: String,
    /// The Go type of the field.
    go: String,
    /// The variant on the wire.
    wire: String,
    /// The variant carries nothing.
    unit: bool,
}

fn emit_data_enum(
    out: &mut String,
    name: &str,
    doc: &[String],
    repr: &EnumRepr,
    variants: &[Variant],
) {
    let fields = dedupe(variants.iter().map(|v| pascal(&v.name)).collect());
    let mut slots = Vec::new();
    // Payload types for struct and tuple variants come first.
    for (v, f) in variants.iter().zip(&fields) {
        let payload = format!("{name}{f}");
        let (go, unit) = match &v.kind {
            VariantKind::Unit => ("bool".to_owned(), true),
            VariantKind::Newtype(t) => (format!("*{}", ty(t)), false),
            VariantKind::Tuple(items) => {
                tuple_type(out, &payload, items, &v.doc);
                out.push('\n');
                (format!("*{payload}"), false)
            }
            VariantKind::Struct(fs) => {
                comment(out, &v.doc, "");
                let _ = writeln!(out, "type {payload} struct {{");
                struct_body(out, fs, &field_names(fs, pascal));
                out.push_str("}\n\n");
                (format!("*{payload}"), false)
            }
        };
        slots.push(Slot {
            field: f.clone(),
            go,
            wire: v.name.clone(),
            unit,
        });
    }
    comment(out, doc, "");
    let _ = writeln!(
        out,
        "// Exactly one variant field is set.\ntype {name} struct {{"
    );
    for s in &slots {
        let _ = writeln!(out, "\t{} {}", s.field, s.go);
    }
    let _ = writeln!(out, "}}\n");

    // Marshal
    let _ = writeln!(
        out,
        "func (v {name}) MarshalJSON() ([]byte, error) {{\n\tswitch {{"
    );
    for s in &slots {
        let cond = if s.unit {
            format!("v.{}", s.field)
        } else {
            format!("v.{} != nil", s.field)
        };
        let _ = writeln!(out, "\tcase {cond}:");
        let w = q(&s.wire);
        let body = match (repr, s.unit) {
            (EnumRepr::External, true) => format!("return json.Marshal({w})"),
            (EnumRepr::External, false) => {
                format!("return json.Marshal(map[string]any{{{w}: v.{}}})", s.field)
            }
            (EnumRepr::Internal { tag }, true) => {
                format!("return wfTagged({}, {w}, struct{{}}{{}})", q(tag))
            }
            (EnumRepr::Internal { tag }, false) => {
                format!("return wfTagged({}, {w}, v.{})", q(tag), s.field)
            }
            (EnumRepr::Adjacent { tag, .. }, true) => {
                format!("return json.Marshal(map[string]any{{{}: {w}}})", q(tag))
            }
            (EnumRepr::Adjacent { tag, content }, false) => {
                format!(
                    "return json.Marshal(map[string]any{{{}: {w}, {}: v.{}}})",
                    q(tag),
                    q(content),
                    s.field
                )
            }
        };
        let _ = writeln!(out, "\t\t{body}");
    }
    let _ = writeln!(
        out,
        "\t}}\n\treturn nil, errors.New(\"{name}: no variant set\")\n}}\n"
    );

    // Unmarshal
    let _ = writeln!(
        out,
        "func (v *{name}) UnmarshalJSON(b []byte) error {{\n\t*v = {name}{{}}"
    );
    let set = |s: &Slot, src: &str| -> String {
        if s.unit {
            format!("\t\tv.{} = true\n\t\treturn nil", s.field)
        } else {
            let inner = s.go.trim_start_matches('*');
            format!(
                "\t\tvar x {inner}\n\t\tif err := json.Unmarshal({src}, &x); err != nil {{\n\t\t\treturn err\n\t\t}}\n\t\tv.{} = &x\n\t\treturn nil",
                s.field
            )
        }
    };
    match repr {
        EnumRepr::External => {
            let _ = writeln!(
                out,
                "\tvar s string\n\tif json.Unmarshal(b, &s) == nil {{\n\t\tswitch s {{"
            );
            for s in slots.iter().filter(|s| s.unit) {
                let _ = writeln!(
                    out,
                    "\t\tcase {}:\n\t\t\tv.{} = true\n\t\t\treturn nil",
                    q(&s.wire),
                    s.field
                );
            }
            let _ = writeln!(
                out,
                "\t\t}}\n\t\treturn fmt.Errorf(\"{name}: unknown variant %q\", s)\n\t}}"
            );
            let _ = writeln!(out, "\tvar m map[string]json.RawMessage\n\tif err := json.Unmarshal(b, &m); err != nil {{\n\t\treturn err\n\t}}\n\tif len(m) != 1 {{\n\t\treturn errors.New(\"{name}: expected an object with exactly one key\")\n\t}}\n\tfor k, raw := range m {{\n\t\tswitch k {{");
            for s in slots.iter().filter(|s| !s.unit) {
                let _ = writeln!(out, "\t\tcase {}:\n{}", q(&s.wire), set(s, "raw"));
            }
            let _ = writeln!(out, "\t\tdefault:\n\t\t\treturn fmt.Errorf(\"{name}: unknown variant %q\", k)\n\t\t}}\n\t}}\n\treturn nil\n}}");
        }
        EnumRepr::Internal { tag } => {
            let _ = writeln!(out, "\tvar m map[string]json.RawMessage\n\tif err := json.Unmarshal(b, &m); err != nil {{\n\t\treturn err\n\t}}\n\tk, err := wfTag(m, {}, \"{name}\")\n\tif err != nil {{\n\t\treturn err\n\t}}\n\tswitch k {{", q(tag));
            for s in &slots {
                let _ = writeln!(out, "\tcase {}:\n{}", q(&s.wire), set(s, "b"));
            }
            let _ = writeln!(
                out,
                "\t}}\n\treturn fmt.Errorf(\"{name}: unknown variant %q\", k)\n}}"
            );
        }
        EnumRepr::Adjacent { tag, content } => {
            let _ = writeln!(out, "\tvar m map[string]json.RawMessage\n\tif err := json.Unmarshal(b, &m); err != nil {{\n\t\treturn err\n\t}}\n\tk, err := wfTag(m, {}, \"{name}\")\n\tif err != nil {{\n\t\treturn err\n\t}}\n\traw := m[{}]\n\tswitch k {{", q(tag), q(content));
            for s in &slots {
                let _ = writeln!(out, "\tcase {}:\n{}", q(&s.wire), set(s, "raw"));
            }
            let _ = writeln!(
                out,
                "\t}}\n\treturn fmt.Errorf(\"{name}: unknown variant %q\", k)\n}}"
            );
        }
    }
}
